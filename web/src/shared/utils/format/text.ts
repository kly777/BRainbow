/** 中文与拉丁/数字之间的留白（《中文文案排版指北》「中英文之間需要增加空格」） */

/**
 * 在汉字与 ASCII 字母/数字的边界补一个空格。
 *
 * 为什么不直接在模板里写死空格：有几处文案的变量**两种文字都可能是**。
 * 例如 `` `${what}里没有可用的点` `` 既会收到 `"PCD"`（拉丁）也会收到
 * `"点云文件"`（中文）—— 模板里写死空格会把中文那边弄错（`"点云文件 里…"`），
 * 不写又会把拉丁那边弄错（`"PCD里…"`）。所以按**最终字符串**补，而不是按模板补。
 * 这正是《中文文案排版指北》列出 pangu / autocorrect 那一类工具要解决的问题。
 *
 * 边界处理：
 * - 只碰 `[ \t]`，**绝不碰换行** —— 消息里的 `\n` 是排版的一部分，不能被压成空格；
 * - 已有空白的折叠成一个（`"PCD 里"` 不会变成 `"PCD  里"`）；
 * - 度数 / 百分号与数字之间本来就不该加空格（指北的例外：`90°`、`15%`），
 *   而这两个符号不在 ASCII 字母数字类里，天然不会被这条匹配到。
 *
 * 只做"该加没加"这一个方向；"不该加却加了"（如全角标点前的空格）目前仓库里没有，
 * 需要时再补。
 */
export function cjkSpace(text: string): string {
	return text
		.replace(/([\u4e00-\u9fff])[ \t]*([A-Za-z0-9])/g, "$1 $2")
		.replace(/([A-Za-z0-9])[ \t]*([\u4e00-\u9fff])/g, "$1 $2");
}
